  // ce que le serveur reçoit : le contenu de la section, chaque îlot réduit à son repère
  function serialize(sec) {
    var c = sec.cloneNode(true);
    Array.prototype.forEach.call(c.querySelectorAll('.ppme-human-review'), function (n) { n.remove(); });
    Array.prototype.forEach.call(c.querySelectorAll('[data-pp-island]'), function (n) {
      if (!n.parentNode) return;
      var mark = document.createElement('span');
      mark.setAttribute('data-pp-island', n.getAttribute('data-pp-island'));
      n.parentNode.replaceChild(mark, n);
    });
    Array.prototype.forEach.call(c.querySelectorAll('[data-ppme-closed]'), function (d) {
      d.removeAttribute('open');
      d.removeAttribute('data-ppme-closed');
    });
    Array.prototype.forEach.call(c.querySelectorAll('*'), function (n) {
      n.removeAttribute('contenteditable');
      n.removeAttribute('spellcheck');
      n.removeAttribute('draggable');
      if (n.classList && n.classList.length) {
        Array.prototype.slice.call(n.classList).forEach(function (k) { if (k.indexOf('ppme-') === 0) n.classList.remove(k); });
        if (!n.classList.length) n.removeAttribute('class');
      }
    });
    return c.innerHTML;
  }
