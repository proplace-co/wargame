  // une opération annulable : l'état avant, l'opération, l'état après
  function change(sids, fn) {
    if (READER) return;
    closeTyping();
    var before = snap(sids);
    doc.busy = true;
    try { fn(); } finally { doc.busy = false; }
    remember({ before: before, after: snap(sids) });
    (sids || []).forEach(function (sid) { doc.touched[sid] = true; });
    afterChange();
  }
  function afterChange() {
    applyPrintMarks();
    renderRail();
    scheduleSave();
    updateBar();
    if (doc.sel) placeMedia();
  }
  function undo() {
    closeTyping();
    var h = doc.history.pop();
    if (!h) return;
    doc.future.push(h);
    applySnap(h.before);
  }
  function redo() {
    closeTyping();
    var h = doc.future.pop();
    if (!h) return;
    doc.history.push(h);
    applySnap(h.after);
  }

  /* enregistrer : une version par enregistrement, sur la dernière version (route /document) */
  function structureChanged() {
    var ids = order();
    var mine = ids.filter(function (sid) { return sid in doc.hashes; });
    var theirs = doc.order.filter(function (sid) { return ids.indexOf(sid) >= 0; });
    return mine.join('|') !== theirs.join('|') || ids.some(function (sid) { return !(sid in doc.hashes); })
      || Object.keys(doc.hashes).some(function (sid) { return ids.indexOf(sid) < 0; });
  }
  function payload() {
    var ids = order(), n = 0;
    var p = { session: doc.session, known: doc.hashes, sections: {}, added: {}, removed: {} };
    sections().forEach(function (sec) {
      if (!(sec.id in doc.hashes)) { p.added[sec.id] = { html: serialize(sec) }; n++; return; }
      if (!doc.touched[sec.id]) return;
      var html = serialize(sec);
      if (html !== doc.saved[sec.id]) { p.sections[sec.id] = { html: html, base: doc.hashes[sec.id] }; n++; }
    });
    Object.keys(doc.hashes).forEach(function (sid) { if (ids.indexOf(sid) < 0) { p.removed[sid] = doc.hashes[sid]; n++; } });
    if (structureChanged()) { p.order = ids; p.order_base = doc.order; n++; }
    var card = byId(CONTACT);
    if (card && doc.touched[CONTACT]) {
      var ch = serialize(card);
      if (ch !== doc.saved[CONTACT]) { p.contact = { html: ch, base: doc.contactHash }; n++; }
    }
    if (doc.contactHash != null) p.known_contact = doc.contactHash;
    var pr = {};
    Object.keys(doc.print).forEach(function (id) { if (doc.print[id] !== doc.printBase[id]) pr[id] = doc.print[id]; });
    if (Object.keys(pr).length) { p.print = pr; n++; }
    return n ? p : null;
  }
  function scheduleSave(delay) {
    if (!doc.on) return;
    clearTimeout(doc.timer);
    if (!doc.since) doc.since = Date.now();
    // 2 s après la dernière modification, au plus tard 15 s après la première
    var wait = Math.max(0, Math.min(delay == null ? 2000 : delay, 15000 - (Date.now() - doc.since)));
    doc.timer = setTimeout(save, wait);
    if (!doc.saving) status('dirty');
  }
  function save(flush) {
    if (READER) return Promise.resolve(true);
    clearTimeout(doc.timer);
    if (!doc.on) return Promise.resolve(true);
    if (doc.cropping) {
      if (flush !== true) { doc.timer = setTimeout(save, 1500); return Promise.resolve(true); }
      endCrop(false);
    }
    closeTyping();
    if (doc.saving) { doc.again = true; return doc.saving; }
    var p = payload();
    doc.since = 0;
    if (!p) { if (doc.state !== 'error' && doc.state !== 'conflict') status('idle'); return Promise.resolve(true); }
    var sent = {}, touched = doc.touched;
    Object.keys(p.sections).forEach(function (k) { sent[k] = p.sections[k].html; });
    Object.keys(p.added).forEach(function (k) { sent[k] = p.added[k].html; });
    if (p.contact) sent[CONTACT] = p.contact.html;
    doc.touched = {};
    status('saving');
    doc.saving = api('/document', 'POST', p).then(function (j) {
      doc.saving = null;
      if (j.ok) {
        Object.keys(sent).forEach(function (k) { doc.saved[k] = sent[k]; });
        adoptServer(j);
        status('saved');
      } else {
        Object.keys(touched).forEach(function (k) { doc.touched[k] = true; });
        if (j.status === 409 && j.conflict) onConflict(j);
        else status('error', j.detail || j.error || j.status);
      }
      if (doc.again) { doc.again = false; scheduleSave(300); }
      return !!j.ok;
    }).catch(function (e) {
      doc.saving = null;
      Object.keys(touched).forEach(function (k) { doc.touched[k] = true; });
      status('error', e);
      return false;
    });
    return doc.saving;
  }
