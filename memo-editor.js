  /* annuler, rétablir : des instantanés (le contenu des sections touchées, les îlots gardés
   * vivants, et le plan) — la frappe, la mise en forme, les blocs et les sections */
  function cloneSection(sec) {
    var frag = document.createDocumentFragment();
    Array.prototype.forEach.call(sec.childNodes, function (n) { frag.appendChild(n.cloneNode(true)); });
    var live = sec.querySelectorAll('[data-pp-island]'), copies = frag.querySelectorAll('[data-pp-island]');
    var keep = [];
    Array.prototype.forEach.call(copies, function (c, i) {
      if (!c.parentNode) return;
      keep.push(live[i]);
      c.parentNode.replaceChild(document.createComment('ppme-i:' + (keep.length - 1)), c);
    });
    return { frag: frag, islands: keep };
  }
  function restoreSection(sec, saved) {
    var frag = saved.frag.cloneNode(true);
    var marks = [], walker = document.createTreeWalker(frag, NodeFilter.SHOW_COMMENT);
    while (walker.nextNode()) if (/^ppme-i:\d+$/.test(walker.currentNode.data)) marks.push(walker.currentNode);
    marks.forEach(function (m) {
      var node = saved.islands[+m.data.slice(7)];
      if (node) m.parentNode.replaceChild(node, m); else m.parentNode.removeChild(m);
    });
    while (sec.firstChild) sec.removeChild(sec.firstChild);
    sec.appendChild(frag);
  }
  function snap(sids) {
    var s = { order: order(), nodes: {}, print: copy(doc.print), content: {} };
    sections().forEach(function (sec) { s.nodes[sec.id] = sec; });
    (sids || []).forEach(function (sid) { var sec = byId(sid); if (sec) s.content[sid] = cloneSection(sec); });
    return s;
  }
  function applySnap(s) {
    Object.keys(s.content).forEach(function (sid) { if (s.nodes[sid]) restoreSection(s.nodes[sid], s.content[sid]); });
    arrange(s.order.map(function (sid) { return s.nodes[sid]; }).filter(Boolean));
    doc.print = copy(s.print);
    Object.keys(s.content).forEach(function (sid) { doc.touched[sid] = true; });
    hideTools();
    afterChange();
  }
  // les sections dans cet ordre, aux places des sections (ce qui les sépare reste où il est)
  function arrange(list) {
    var cur = sections();
    if (cur.length === list.length && cur.every(function (s, i) { return s === list[i]; })) return;
    var slots = cur.map(function (sec) { var m = document.createComment('ppme-slot'); sec.parentNode.insertBefore(m, sec); return m; });
    cur.forEach(function (sec) { sec.parentNode.removeChild(sec); });
    var prev = null;
    list.forEach(function (sec, i) {
      if (i < slots.length) slots[i].parentNode.insertBefore(sec, slots[i]);
      else if (prev) prev.parentNode.insertBefore(sec, prev.nextSibling);
      else area.appendChild(sec);
      prev = sec;
    });
    slots.forEach(function (m) { m.parentNode.removeChild(m); });
  }
  function remember(entry) {
    doc.history.push(entry);
    if (doc.history.length > 60) doc.history.shift();
    doc.future = [];
    updateBar();
  }
