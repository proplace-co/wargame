  function printPack() {
    hideTools();
    closeMenu();
    var named = document.querySelector('.sidebar-company-name');
    var name = String(state.company || ctx.name || ctx.company_name || (named && named.textContent) || '').trim();
    var head = state.head || {};
    var kept = sections().filter(function (sec) { return !printOff(sec.id); });
    var cover = el('section', { class: 'ppme-print-cover' });
    cover.appendChild(el('span', { class: 'ppme-print-k' }, 'PROPLACE · ' + P.kicker + (state.fund ? ' · ' + state.fund : '')));
    cover.appendChild(el('h1', {}, name));
    if (head.n) cover.appendChild(el('p', {}, head.kind === 'generated' ? P.published(when(head.at)) : P.version(head.n, shortWho(head.by), when(head.at))));
    if (kept.length) {
      cover.appendChild(el('h2', {}, P.toc));
      var toc = el('ol', { class: 'ppme-print-toc' });
      kept.forEach(function (sec) { toc.appendChild(el('li', {}, titleOf(sec))); });
      cover.appendChild(toc);
    }
    area.insertBefore(cover, area.firstChild);
    var hidden = sections().filter(function (sec) { return printOff(sec.id); });
    // comme le dossier comité du cockpit : l'analyse d'abord, la fiche contact en dernier
    var contact = contactCard();
    var place = contact && { parent: contact.parentNode, next: contact.nextSibling };
    if (contact) {
      if (printOff('fiche-contact')) hidden.push(contact);
      area.appendChild(contact);
    }
    hidden.forEach(function (n) { n.classList.add('ppme-print-off'); });
    var closed = Array.prototype.filter.call(area.querySelectorAll('details'), function (d) { return !d.open; });
    closed.forEach(function (d) { d.open = true; });
    Array.prototype.forEach.call(area.querySelectorAll('img[loading="lazy"]'), function (i) { i.loading = 'eager'; });
    var title = document.title;
    document.title = P.file(name, head.n);
    function restore() {
      cover.remove();
      hidden.forEach(function (n) { n.classList.remove('ppme-print-off'); });
      if (place) place.parent.insertBefore(contact, place.next && place.next.parentNode === place.parent ? place.next : null);
      closed.forEach(function (d) { d.open = false; });
      document.title = title;
      window.removeEventListener('afterprint', restore);
    }
    window.addEventListener('afterprint', restore);
    imagesReady(area, 8000).then(function () { window.print(); });
  }

